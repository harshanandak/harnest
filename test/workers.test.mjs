for (const key of TARGETS) {
  test(`opencode-agents/${key}-worker.md shares the Claude shell spine`, async () => {
    const md = await readFile(join(agentsDir, `${key}-worker.md`), "utf8");
    const oc = await readFile(join(opencodeDir, `${key}-worker.md`), "utf8");
    const stripFrontmatter = (text) => text.slice(text.indexOf("---\n", 3) + 4);
    const expected = stripFrontmatter(md)
      .replaceAll("Claude's", "this OpenCode session's")
      .replaceAll("Your Claude subagent thread", "Your OpenCode child session")
      .replaceAll("`handoff_", "`harnest_handoff_")
      .replaceAll(
        "handoff_message/handoff_reroute fail closed as unsupported-control",
        "`harnest_handoff_message`/`harnest_handoff_reroute` fail closed as `unsupported-control`",
      );
    assert.equal(stripFrontmatter(oc), expected);
  });
}

