test("builder regenerates all worker files identically (no hand edits)", async () => {
  const files = [
    ...TARGETS.map((key) => join(agentsDir, `${key}-worker.md`)),
    join(agentsDir, "workflow-rescue.md"),
    ...["pi", "opencode", "cursor", "claude", "gemini", "amp", "acp"].map((key) => join(codexDir, `${key}_worker.toml`)),
    ...TARGETS.map((key) => join(opencodeDir, `${key}-worker.md`)),
  ];
  const before = await Promise.all(files.map((file) => readFile(file, "utf8")));
  await new Promise((resolve, reject) => {
    execFile(process.execPath, [join(root, "scripts", "build-workers.mjs")], (error, stdout, stderr) => {
      if (error) reject(new Error(`builder failed: ${stderr || error.message}`));
      else resolve(stdout);
    });
  });
  const after = await Promise.all(files.map((file) => readFile(file, "utf8")));
  assert.deepEqual(after, before);
});
