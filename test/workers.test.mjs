// Bridge-worker coherence: one builder emits all three host shells (Claude
// .md + Codex .toml + OpenCode .md) from the same per-target blocks, so every
// harness delivers the same reference experience — visible child, per-poll
// progress, steerable at any point, verbatim terminal receipt.
import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { readFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import test from "node:test";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const agentsDir = join(root, "agents");
const codexDir = join(root, "codex-agents");
const opencodeDir = join(root, "opencode-agents");

const TARGETS = ["pi", "opencode", "cursor", "claude", "codex", "gemini", "amp", "acp"];
const OPENCODE_COLOR = { pi: "accent", opencode: "info", cursor: "accent", claude: "accent", codex: "accent", gemini: "accent", amp: "accent", acp: "accent" };
const OPENCODE_STEPS = { pi: 120, opencode: 120, cursor: 60, claude: 60, codex: 60, gemini: 60, amp: 60, acp: 60 };
const VERIFY = {
  pi: "Pi session or workflow identity",
  opencode: "OpenCode session or workflow identity",
  cursor: "Cursor session/workflow identity",
  claude: "Claude session/workflow identity",
  codex: "Codex session/workflow identity",
  gemini: "Gemini session/workflow identity",
  amp: "Amp session/workflow identity",
  acp: "ACP agent and native session identity",
};

function frontmatter(text) {
  const match = /^---\n([\s\S]*?)\n---\n/.exec(text);
  assert.ok(match, "Claude worker must have YAML frontmatter");
  return match[1];
}

test("handoff skills honor the user's model choice", async () => {
  for (const path of ["skills/handoff/SKILL.md", ".cursor/skills/handoff/SKILL.md"]) {
    const skill = await readFile(join(root, path), "utf8");
    assert.match(skill, /Use the model the user names in `route\.model` and any effort they name in `route\.thinking`/);
    assert.match(skill, /If the user names an exact model ID, set `metadata.routing.modelVersion` to `pin`/);
    assert.match(skill, /Leave native aliases such as `sonnet` or `opus` unpinned/);
    assert.match(skill, /use their saved routing preferences/);
    assert.match(skill, /omit `route\.model` so the downstream CLI can use its configured default/);
    assert.doesNotMatch(skill, /\bgpt-6\.[12]-(?:sol|terra)\b/i);
  }
});

for (const key of TARGETS) {
  test(`agents/${key}-worker.md delivers the reference experience`, async () => {
    const raw = await readFile(join(agentsDir, `${key}-worker.md`), "utf8");
    const head = frontmatter(raw);
    assert.match(head, new RegExp(`name: ${key}-worker`));
    assert.match(head, /disallowedTools: Agent, Bash/);
    assert.match(head, /harnest:handoff/);
    assert.match(head, /background: true/);
    assert.match(raw, /thin forwarder, not an orchestrator/);
    assert.match(raw, /exactly one `handoff_workflow` call/);
    assert.match(raw, /first visible message announces the job ID and request ID/);
    assert.match(raw, /After EVERY poll, emit one short visible update/);
    assert.match(raw, /heartbeat-only activity is stalled, not progress/);
    assert.match(raw, /Never end the turn before terminal state/);
    assert.ok(raw.includes(VERIFY[key]), `must verify ${VERIFY[key]}`);
    assert.match(raw, /return the complete receipt to the parent/);
    assert.match(raw, /never merges, deploys/);
    assert.match(raw, /Fan-out belongs to the parent: at most 6 concurrent workers/);
    assert.match(raw, /never spawns workers/);
    if (key === "codex") {
      assert.match(raw, /never danger-full-access, never --dangerously-bypass-approvals/);
    } else {
      assert.doesNotMatch(raw, /danger-full-access|dangerously-bypass/);
    }
  });
}

for (const key of ["pi", "opencode", "cursor", "claude", "gemini", "amp", "acp"]) {
  test(`codex-agents/${key}_worker.toml matches its Claude shell`, async () => {
    const toml = await readFile(join(codexDir, `${key}_worker.toml`), "utf8");
    const md = await readFile(join(agentsDir, `${key}-worker.md`), "utf8");
    assert.match(toml, /GENERATED by scripts\/build-workers\.mjs/);
    assert.match(toml, new RegExp(`name = "${key}_worker"`));
    assert.match(toml, /sandbox_mode = "read-only"/);
    assert.match(toml, /^model_reasoning_effort\s*=\s*"high"/m);
    assert.doesNotMatch(toml, /^\s*model\s*=/m);
    // Same contract, host shell nouns aside: strip backticks + Claude/Codex
    // thread nouns, then require the shared spine in both.
    const spine = [
      "thin forwarder, not an orchestrator",
      "first visible message announces the job ID and request ID",
      "After EVERY poll, emit one short",
      "heartbeat-only activity is stalled, not progress",
      "Never end the turn before terminal state",
      "never merges, deploys",
    ];
    for (const line of spine) {
      assert.ok(toml.includes(line), `toml missing: ${line}`);
      assert.ok(md.includes(line), `md missing: ${line}`);
    }
    if (key === "pi") {
      assert.match(md, /Claude models never run here/);
      assert.match(toml, /Claude models never run here/);
    }
    assert.ok(toml.includes(VERIFY[key]) && md.includes(VERIFY[key]));
  });
}

